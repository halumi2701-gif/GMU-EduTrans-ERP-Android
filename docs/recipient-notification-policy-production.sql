-- GMU EduTrans ERP — Recipient & Notification Policy Production Bundle
-- Safe staged source. Apply only through an authenticated Supabase admin/MCP session,
-- then deploy supabase/functions/gmu-recipient-policy-admin and run the verification queries below.
--
-- Goals:
-- 1) Reuse gmu_erp.user_notification (no parallel inbox table).
-- 2) Finance receives PAYMENT_RECORDED by role.
-- 3) TL receives TRIP_ASSIGNMENT only when recipient_user_id = assigned TL auth UUID.
-- 4) Android never reads gmu_erp.user_notification directly; the Edge Function is the policy boundary.
-- 5) RPCs are callable only by service_role and therefore only through the verified Edge Function.

begin;

