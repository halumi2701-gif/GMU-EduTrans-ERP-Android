create or replace function private.notification_role_match(
  p_profile_role text,
  p_target_role text
)
returns boolean
language sql
immutable
set search_path=''
as $$
  select case upper(coalesce(p_target_role,''))
    when 'ANY' then true
    when 'DIRECTOR' then coalesce(p_profile_role,'') in ('Director','Direktur')
    when 'MANAGER EDUTRANS' then coalesce(p_profile_role,'') in ('Manager EduTrans','Manager')
    else lower(coalesce(p_profile_role,'')) = lower(coalesce(p_target_role,''))
  end;
$$;

create or replace function private.notification_severity_rank(p text)
returns integer
language sql
immutable
set search_path=''
as $$
  select case upper(coalesce(p,''))
    when 'CRITICAL' then 3
    when 'WARNING' then 2
    else 1
  end;
$$;

create or replace function private.try_uuid(p text)
returns uuid
language plpgsql
immutable
set search_path=''
as $$
begin
  if p is null or btrim(p) = '' then return null; end if;
  return p::uuid;
exception when invalid_text_representation then
  return null;
end;
$$;

-- Payment -> Finance role routing.
create or replace function private.emit_payment_recipient_notification()
returns trigger
language plpgsql
security definer
set search_path='public','gmu_erp','private','pg_temp'
as $$
declare
  pol record;
  j jsonb := to_jsonb(new);
  v_id text;
  v_booking text;
  v_type text;
  v_amount numeric;
begin
  v_id := coalesce(j->>'id', md5(clock_timestamp()::text || random()::text));
  v_booking := nullif(j->>'booking_id','');
  v_type := coalesce(j->>'payment_type', j->>'method', 'Payment');
  begin
    v_amount := coalesce(nullif(j->>'amount','')::numeric, 0);
  exception when others then
    v_amount := 0;
  end;

  for pol in
    select *
    from public.notification_recipient_policies
    where event_key='PAYMENT_RECORDED'
      and is_active=true
      and recipient_scope='ROLE'
      and private.notification_severity_rank('INFO') >= private.notification_severity_rank(min_severity)
  loop
    if not exists (
      select 1 from gmu_erp.user_notification n
      where n.source_key='PAYMENT_RECORDED:'||v_id
        and lower(coalesce(n.target_role,''))=lower(pol.target_role)
        and n.recipient_user_id is null
    ) then
      insert into gmu_erp.user_notification
      (target_role,recipient_user_id,event_key,title,message,severity,link,source_key,booking_id,is_read,created_at)
      values
      (
        pol.target_role,
        null,
        'PAYMENT_RECORDED',
        'Pembayaran tercatat',
        'Pembayaran '||v_type||' sebesar Rp'||to_char(v_amount,'FM999G999G999G990')||
          case when v_booking is null then '.' else ' tercatat untuk booking '||v_booking||'.' end,
        'INFO',
        'DASHBOARD',
        'PAYMENT_RECORDED:'||v_id,
        v_booking,
        false,
        now()
      );
    end if;
  end loop;
  return new;
end;
$$;

-- Trip assignment -> exactly one assigned TL auth UUID.
create or replace function private.emit_trip_assignment_recipient_notification()
returns trigger
language plpgsql
security definer
set search_path='public','gmu_erp','private','pg_temp'
as $$
declare
  pol record;
  j_new jsonb := to_jsonb(new);
  j_old jsonb;
  v_trip_id text;
  v_booking text;
  v_new_tl uuid;
  v_old_tl uuid;
  v_key text;
begin
  if tg_op <> 'INSERT' then j_old := to_jsonb(old); end if;

  v_trip_id := coalesce(j_new->>'id', md5(clock_timestamp()::text || random()::text));
  v_booking := nullif(j_new->>'booking_id','');
  v_new_tl := private.try_uuid(j_new->>'tl_id');
  v_old_tl := case when tg_op='INSERT' then null else private.try_uuid(j_old->>'tl_id') end;

  if v_new_tl is null or v_new_tl is not distinct from v_old_tl then
    return new;
  end if;

  v_key := 'TRIP_ASSIGNMENT:'||v_trip_id||':'||v_new_tl::text;

  for pol in
    select *
    from public.notification_recipient_policies
    where event_key='TRIP_ASSIGNMENT'
      and is_active=true
      and recipient_scope='ASSIGNED_USER'
      and target_role='TL'
      and private.notification_severity_rank('INFO') >= private.notification_severity_rank(min_severity)
  loop
    if not exists (
      select 1 from gmu_erp.user_notification n
      where n.source_key=v_key
        and n.recipient_user_id=v_new_tl
    ) then
      insert into gmu_erp.user_notification
      (target_role,recipient_user_id,event_key,title,message,severity,link,source_key,booking_id,is_read,created_at)
      values
      (
        'TL',
        v_new_tl,
        'TRIP_ASSIGNMENT',
        'Anda ditugaskan sebagai TL',
        'Penugasan trip'||case when v_booking is null then '' else ' untuk booking '||v_booking end||
          '. Buka Operations untuk melihat kesiapan trip.',
        'INFO',
        'OPERATIONS',
        v_key,
        v_booking,
        false,
        now()
      );
    end if;
  end loop;

  return new;
end;
$$;

-- Install triggers only if the production tables/columns are present.
do $install_triggers$
begin
  if to_regclass('public.payments') is not null then
    execute 'drop trigger if exists trg_payment_recipient_notification on public.payments';
    execute 'create trigger trg_payment_recipient_notification after insert on public.payments for each row execute function private.emit_payment_recipient_notification()';
  end if;

  if to_regclass('public.trips') is not null and exists (
    select 1 from information_schema.columns
    where table_schema='public' and table_name='trips' and column_name='tl_id'
  ) then
    execute 'drop trigger if exists trg_trip_assignment_recipient_notification on public.trips';
    execute 'create trigger trg_trip_assignment_recipient_notification after insert or update of tl_id on public.trips for each row execute function private.emit_trip_assignment_recipient_notification()';
  end if;
end
$install_triggers$;

-- Service-only RPC used by gmu-recipient-policy-admin.
-- IDs are returned as text so the contract remains safe whether a legacy inbox uses bigint or uuid IDs.
create or replace function public.gmu_staff_notification_inbox(
  p_user_id uuid,
  p_role text,
  p_limit integer default 30
)
returns table (
  id text,
  event_key text,
  severity text,
  title text,
  message text,
  booking_id text,
  target_page text,
  is_read boolean,
  created_at timestamptz
)
language sql
security definer
set search_path='public','gmu_erp','private','pg_temp'
as $$
  select
    n.id::text,
    coalesce(nullif(n.event_key,''), split_part(coalesce(n.source_key,''),':',1), 'ERP_NOTIFICATION') as event_key,
    coalesce(nullif(n.severity,''),'INFO') as severity,
    coalesce(n.title,'Notifikasi ERP') as title,
    coalesce(n.message,'') as message,
    coalesce(n.booking_id,'') as booking_id,
    coalesce(nullif(n.link,''),'DASHBOARD') as target_page,
    coalesce(n.is_read,false) as is_read,
    n.created_at
  from gmu_erp.user_notification n
  where private.notification_role_match(p_role,n.target_role)
    and (
      case
        when coalesce(nullif(n.event_key,''), split_part(coalesce(n.source_key,''),':',1))='TRIP_ASSIGNMENT'
          then n.recipient_user_id = p_user_id
        else n.recipient_user_id is null or n.recipient_user_id = p_user_id
      end
    )
  order by n.created_at desc
  limit greatest(1,least(coalesce(p_limit,30),100));
$$;

create or replace function public.gmu_staff_notification_mark_read(
  p_id text,
  p_user_id uuid,
  p_role text
)
returns boolean
language plpgsql
security definer
set search_path='public','gmu_erp','private','pg_temp'
as $$
declare
  v_count integer;
begin
  update gmu_erp.user_notification n
  set is_read=true,
      read_at=coalesce(n.read_at,now())
  where n.id::text=p_id
    and private.notification_role_match(p_role,n.target_role)
    and (
      case
        when coalesce(nullif(n.event_key,''), split_part(coalesce(n.source_key,''),':',1))='TRIP_ASSIGNMENT'
          then n.recipient_user_id = p_user_id
        else n.recipient_user_id is null or n.recipient_user_id = p_user_id
      end
    );
  get diagnostics v_count = row_count;
  return v_count > 0;
end;
$$;

create or replace function public.gmu_staff_notification_mark_all_read(
  p_user_id uuid,
  p_role text
)
returns integer
language plpgsql
security definer
set search_path='public','gmu_erp','private','pg_temp'
as $$
declare
  v_count integer;
begin
  update gmu_erp.user_notification n
  set is_read=true,
      read_at=coalesce(n.read_at,now())
  where coalesce(n.is_read,false)=false
    and private.notification_role_match(p_role,n.target_role)
    and (
      case
        when coalesce(nullif(n.event_key,''), split_part(coalesce(n.source_key,''),':',1))='TRIP_ASSIGNMENT'
          then n.recipient_user_id = p_user_id
        else n.recipient_user_id is null or n.recipient_user_id = p_user_id
      end
    );
  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

