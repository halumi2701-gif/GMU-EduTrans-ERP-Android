create schema if not exists gmu_erp;

-- Existing ERP inbox is reused. The CREATE is only a fallback for environments where it is absent.
create table if not exists gmu_erp.user_notification (
  id bigint generated by default as identity primary key,
  target_role text not null,
  title text not null,
  message text not null default '',
  severity text not null default 'INFO',
  link text not null default 'DASHBOARD',
  source_key text,
  created_at timestamptz not null default now()
);

-- Additive metadata needed for secure recipient routing. These statements do not remove legacy columns.
alter table gmu_erp.user_notification add column if not exists recipient_user_id uuid;
alter table gmu_erp.user_notification add column if not exists event_key text;
alter table gmu_erp.user_notification add column if not exists booking_id text;
alter table gmu_erp.user_notification add column if not exists is_read boolean not null default false;
alter table gmu_erp.user_notification add column if not exists read_at timestamptz;

create index if not exists idx_user_notification_role_created
  on gmu_erp.user_notification(target_role, created_at desc);
create index if not exists idx_user_notification_recipient_created
  on gmu_erp.user_notification(recipient_user_id, created_at desc)
  where recipient_user_id is not null;
create index if not exists idx_user_notification_source_key
  on gmu_erp.user_notification(source_key)
  where source_key is not null;

create table if not exists public.notification_recipient_policies (
  id uuid primary key default gen_random_uuid(),
  event_key text not null,
  label text not null,
  target_role text not null,
  recipient_scope text not null default 'ROLE'
    check (recipient_scope in ('ROLE','REQUESTER','ASSIGNED_USER')),
  min_severity text not null default 'INFO'
    check (min_severity in ('INFO','WARNING','CRITICAL')),
  is_active boolean not null default true,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(event_key,target_role,recipient_scope)
);

alter table public.notification_recipient_policies enable row level security;
revoke all on public.notification_recipient_policies from anon, authenticated;

